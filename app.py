if not 대장_경로.exists():
    st.info("data/하자대장.csv가 없습니다. 먼저 `python run.py`로 접수함을 처리하세요.")
    st.stop()

대장 = pd.read_csv(대장_경로, dtype=str, encoding="utf-8-sig").fillna("")

# --- 요약 (주간 보고 분류와 같은 기준) ---
c = st.columns(5)
c[0].metric("전체", len(대장))
c[1].metric("긴급", int((대장["긴급도"] == "긴급").sum()))
c[2].metric("업체 요청(보증내)", int((대장["보증판정"] == "보증내").sum()))
c[3].metric("자체보수", int((대장["보증판정"] == "보증만료").sum()))
c[4].metric("확인필요", int((대장["상태"] == "확인필요").sum()))

# --- 점검 ---
