def 적용된_가정(행: pd.Series) -> list[str]:
    """이 행에 어떤 가정이 쓰였는지."""
    번호 = ["W1", "W2"]
    if 행["상태"] == "판정완료":
        번호 += ["W3", "A4"]
        if "만료임박" in 행["비고"]:
            번호.append("W4")
    elif 행["상태"] == "확인필요":
        번호 += ["W5", "A2"]
        if "/" in 행["공종"]:
            번호.append("A1")
        if "맞는 공사" in 행["비고"]:
            번호.append("A3")
        if "처리 실패" in 행["비고"]:
            번호.append("A11")
    if 행["상태"] in ("판정완료", "확인필요"):
        번호.append("A10")
    return 번호


